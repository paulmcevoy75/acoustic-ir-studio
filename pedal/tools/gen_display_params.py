#!/usr/bin/env python3
"""Generate display/PureIR_Display/params_table.h from src/params.h so the
display always shows the same names, ranges and units as the firmware."""
import re, os
root = os.path.join(os.path.dirname(__file__), '..')
src = open(os.path.join(root, 'src', 'params.h')).read()
body = src[src.index('kParamDefs[kNumParams] = {'):]
body = body[:body.index('};')]
rows = re.findall(r'\{"([^"]+)",\s*"([^"]*)",\s*(-?[\d.]+)f,\s*(-?[\d.]+)f,\s*(-?[\d.]+)f,\s*(kLin|kExp)\}', body)
assert len(rows) == 18, len(rows)
banks = re.findall(r'kBankNames\[kNumBanks\]\s*=\s*\{([^}]*)\}', src)[0]
engines = re.findall(r'kEngineNames\[4\]\s*=\s*\{([^}]*)\}', src)[0]
out = ["// GENERATED by tools/gen_display_params.py from src/params.h - do not edit.",
       "#pragma once",
       "struct DParam { const char* name; const char* unit; float lo, hi; bool exp; };",
       "static const DParam kDParams[18] = {"]
for n, u, lo, hi, d, c in rows:
    out.append(f'  {{"{n}", "{u}", {lo}f, {hi}f, {"true" if c == "kExp" else "false"}}},')
out.append("};")
out.append(f"static const char* const kDBanks[3] = {{{banks.strip()}}};")
out.append(f"static const char* const kDEngines[4] = {{{engines.strip()}}};")
open(os.path.join(root, 'display', 'PureIR_Display', 'params_table.h'), 'w').write("\n".join(out) + "\n")
print("ok")
