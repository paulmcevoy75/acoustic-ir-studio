#!/usr/bin/env python3
"""Generate src/ir_builtin.h: the IRs that are compiled into the firmware.

  python3 tools/ir2header.py                      # neutral + synthetic demo body
  python3 tools/ir2header.py a.wav b.wav ...      # your own IRs, plus neutral
  python3 tools/ir2header.py --max-sec 1.0 a.wav  # cap length (default 1.5 s)
  python3 tools/ir2header.py --neutral-last "My Guitar 1s=u.wav" "My Guitar 0.5s=l.wav"
        # "Label=file.wav" sets the name shown on the display; --neutral-last makes the
        # first IR the one that is used at power-up when there is no SD card
Float WAV files (the Acoustic IR Builder's 32-bit float export) are read directly.

The built-in IRs are only a fallback for when no SD card is present.  They are
stored as 16-bit mono at 48 kHz (flash/RAM is small), so keep them short;
full-length IRs belong on the SD card (copy the .wav files to /IR).
"""
import argparse, os, re, sys
import numpy as np
from scipy.io import wavfile
from scipy.signal import resample_poly
from math import gcd

def demo_body(fs=48000, sec=0.7, seed=7):
    """A made-up guitar-body-like response (NOT a measurement of any real guitar)."""
    rng = np.random.default_rng(seed)
    n = int(fs * sec)
    t = np.arange(n) / fs
    modes = [(98, 6, 1.0), (195, 8, 0.8), (285, 10, 0.55), (410, 12, 0.5),
             (560, 14, 0.35), (780, 18, 0.3), (1150, 22, 0.2), (1700, 28, 0.15)]
    h = np.zeros(n)
    for f, d, a in modes:
        h += a * np.exp(-d * t) * np.sin(2 * np.pi * f * t + rng.uniform(0, 6.28))
    # diffuse tail: noise, brighter early, darker late
    noise = rng.standard_normal(n)
    from scipy.signal import butter, lfilter
    b, a = butter(2, 5000 / (fs / 2))
    noise = lfilter(b, a, noise)
    h += 0.08 * noise * np.exp(-9 * t)
    h[0] += 0.5
    h /= np.max(np.abs(h))
    return h, fs

def load(path, max_sec):
    fs, x = wavfile.read(path)
    x = x.astype(np.float64)
    if x.dtype.kind == 'i' or np.issubdtype(x.dtype, np.integer):
        pass
    if x.ndim > 1:
        x = x.mean(axis=1)
    peak = np.max(np.abs(x))
    if peak == 0:
        raise SystemExit(f"{path}: silent")
    x = x / peak
    return x, fs

def to48k(x, fs):
    if fs != 48000:
        g = gcd(fs, 48000)
        x = resample_poly(x, 48000 // g, fs // g)
    return x

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('wavs', nargs='*')
    ap.add_argument('--max-sec', type=float, default=1.5)
    ap.add_argument('--neutral-last', action='store_true', help='put the pass-through Neutral IR after your IRs')
    ap.add_argument('-o', '--out', default=os.path.join(os.path.dirname(__file__), '..', 'src', 'ir_builtin.h'))
    a = ap.parse_args()

    irs = [("Neutral", np.concatenate(([1.0], np.zeros(63))))]
    if not a.wavs:
        h, fs = demo_body()
        irs.append(("Demo Body", h))
    mine = []
    for p in a.wavs:
        label = None
        if '=' in p:
            label, p = p.split('=', 1)
        x, fs = load(p, a.max_sec)
        x = to48k(x, fs)[:int(a.max_sec * 48000)]
        name = label or os.path.splitext(os.path.basename(p))[0]
        name = re.sub(r'[^A-Za-z0-9 _.-]', '_', name)[:20]
        mine.append((name, x / np.max(np.abs(x))))
    if a.neutral_last:
        irs = mine + irs
    else:
        irs = irs + mine

    lines = ["// GENERATED by tools/ir2header.py - do not edit.",
             "#pragma once", "#include <cstddef>", "#include <cstdint>", "namespace pureir", "{",
             "struct BuiltinIr { const char* name; const int16_t* data; size_t length; uint32_t rate; };"]
    for i, (name, x) in enumerate(irs):
        q = np.clip(np.round(x * 32767), -32768, 32767).astype(np.int16)
        body = ",".join(str(int(v)) for v in q)
        lines.append(f"static const int16_t kBuiltinData{i}[] = {{{body}}};")
    lines.append("static const BuiltinIr kBuiltinIrs[] = {")
    for i, (name, x) in enumerate(irs):
        lines.append(f'    {{"{name}", kBuiltinData{i}, {len(x)}, 48000}},')
    lines.append("};")
    lines.append(f"constexpr int kBuiltinIrCount = {len(irs)};")
    lines.append("} // namespace pureir")
    with open(a.out, 'w') as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {a.out}: " + ", ".join(f"{n} ({len(x)} samples)" for n, x in irs))

if __name__ == '__main__':
    main()
